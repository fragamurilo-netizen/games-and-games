def qcurve(a, c, b, n=6):
    return [((1 - t) ** 2 * a[0] + 2 * (1 - t) * t * c[0] + t * t * b[0], (1 - t) ** 2 * a[1] + 2 * (1 - t) * t * c[1] + t * t * b[1]) for t in [k / n for k in range(n)]]
def locks(pts, bend=0.35):
    """Mechas em labareda: de cada vale até a ponta uma curva que estufa para fora e volta reta."""
    out = []
    for i in range(0, len(pts) - 2, 2):
        v, t, v2 = pts[i], pts[i + 1], pts[i + 2]
        mx, my = (v[0] + t[0]) / 2, (v[1] + t[1]) / 2
        dx, dy = t[0] - v[0], t[1] - v[1]
        out += qcurve(v, (mx - dy * bend, my + dx * bend), t, 5)
        out += qcurve(t, ((t[0] + v2[0]) / 2, (t[1] + v2[1]) / 2), v2, 2)
    return out
